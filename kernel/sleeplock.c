void
initsleeplock(struct sleeplock *lk, char *name)
{
  initlock(&lk->lk, "sleep lock");
  lk->name = name;
  lk->locked = 0;
  lk->pid = 0;
}

// 和自旋锁不同，睡眠锁获取不到会睡眠（让出 CPU）
// 因为读磁盘慢，不能忙等
void
acquiresleep(struct sleeplock *lk)
{
  // 加自旋锁
  acquire(&lk->lk);
  while (lk->locked) {
    // lk是睡眠锁  lk->lk是自旋锁
    sleep(lk, &lk->lk);
  }
  lk->locked = 1;
  lk->pid = myproc()->pid;
  release(&lk->lk);
}

void
releasesleep(struct sleeplock *lk)
{
  acquire(&lk->lk);
  lk->locked = 0;
  lk->pid = 0;
  wakeup(lk);
  release(&lk->lk);
}

int
holdingsleep(struct sleeplock *lk)
{
  int r;
  
  acquire(&lk->lk);
  r = lk->locked && (lk->pid == myproc()->pid);
  release(&lk->lk);
  return r;
}



